// src/utils/plural.ts
//
// Русское склонение существительного при числе.
//
// «6 Региона» в карточке узла — не мелочь стиля: подпись, не согласованная с
// числом, читается как ошибка программы и подрывает доверие к самому числу.
// А чисел в интерфейсе много, и подписи у них разные.

/**
 * Выбрать форму по числу: 1 регион, 2 региона, 5 регионов.
 *
 * Правило русского счёта: на 11–14 всегда множественное («11 регионов»),
 * иначе решает последняя цифра. Проверяется именно на этих числах — «11» и
 * «111» ломают наивную проверку по последней цифре.
 */
export function plural(n: number, one: string, few: string, many: string): string {
  const abs = Math.abs(Math.trunc(n));
  const tail100 = abs % 100;
  if (tail100 >= 11 && tail100 <= 14) return many;
  const tail10 = abs % 10;
  if (tail10 === 1) return one;
  if (tail10 >= 2 && tail10 <= 4) return few;
  return many;
}
