// src/utils/inferLayoutDirection.ts
import type { Edge } from "@xyflow/react";
import type { CustomNode } from "../types";

/**
 * Определяет вертикальную ориентацию графа по ФАКТИЧЕСКИМ позициям узлов:
 * "TB" — конец ребра ниже начала (канон «сырьё → продукт», сверху вниз),
 * "BT" — конец выше начала.
 *
 * Зачем: направление рёбер само по себе ориентацию не задаёт. У «вверх»-графов
 * рёбра топологически перевёрнуты (продукт → сырьё, см. orientByBuildDirection),
 * поэтому раскладка с жёстким rankdir "TB" ставит продукт сверху, а сырьё снизу —
 * зеркально тому, что пользователь видит на полотне. Загруженные графы вдобавок
 * рендерятся с сохранёнными позициями и вообще не перераскладываются, так что
 * единственный надёжный источник истины об ориентации — сама геометрия.
 *
 * Считаем по всему графу (а не по подграфу): выборка больше, результат
 * устойчивее на ветках, где рёбра случайно легли иначе.
 */
export function inferLayoutDirection(
  nodes: CustomNode[],
  edges: Edge[],
): "TB" | "BT" {
  const posById = new Map(nodes.map((n) => [n.id, n.position]));

  let down = 0;
  let up = 0;
  for (const e of edges) {
    const s = posById.get(e.source);
    const t = posById.get(e.target);
    if (!s || !t) continue;
    // Порог гасит горизонтальные рёбра (узлы одного яруса) и дребезг позиций.
    const dy = t.y - s.y;
    if (dy > 1) down++;
    else if (dy < -1) up++;
  }

  // Ничья и пустой граф → канон «сверху вниз».
  return up > down ? "BT" : "TB";
}
