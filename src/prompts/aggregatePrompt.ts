export const STEP_AGG_PROMPT_SEPARATOR =
  "\n\n═══════════════════════════════════\nUSER PROMPT (шаблон без блоков — блоки добавляются автоматически)\n═══════════════════════════════════\n\n";

export function getDefaultStepAggregateFullPrompt(
  direction?: "up" | "down",
  productName?: string,
): string {
  return (
    getDefaultStepAggregateSystemPrompt(direction, productName) +
    STEP_AGG_PROMPT_SEPARATOR +
    getDefaultStepAggregateUserPrompt(direction, productName)
  );
}

export function splitStepAggregatePrompt(full: string): {
  system: string;
  user: string;
} {
  const idx = full.indexOf(STEP_AGG_PROMPT_SEPARATOR);
  if (idx === -1) {
    return { system: full.trim(), user: "" };
  }
  return {
    system: full.slice(0, idx).trim(),
    user: full.slice(idx + STEP_AGG_PROMPT_SEPARATOR.length).trim(),
  };
}
