function buildSourcesPrompt(productName: string, maxItems: number): string {
  return `
## Роль и задача

Ты — инженер-технолог (process engineer). Твоя задача: найти открытые источники, где ЯВНО описана промышленная технология/процесс получения (manufacturing / production process) продукта: "${productName}", и извлечь из каждого источника МАКСИМАЛЬНО ПОДРОБНОЕ технологическое описание процесса.

## Что считать "описанием технологии"
Технологическое описание = разбор самого процесса (как он устроен), максимально подробно:
- ключевые стадии/узлы (подготовка сырья → реакция/синтез → разделение → очистка → финиширование/сушка/грануляция и т.п.);
- основные реагенты/сырьё/растворители/катализаторы/ингибиторы;
- оборудование/аппараты (если указаны: тип реактора, колонны, сепараторы, фильтры, сушилки, скрубберы и т.д.);
- условия/параметры (если указаны: T, P, время/проживание, концентрации, соотношения потоков, pH, вакуум и т.д.);
- побочные продукты/примеси и как их удаляют (если указано);
- варианты схемы/альтернативные маршруты, если источник их явно описывает.

⚠️ Нельзя писать: "в статье рассматривается…", "авторы обсуждают…", "работа посвящена…".
Нужно писать: "Процесс включает…", "Сырьё подают…", "Реакцию ведут…", "Поток направляют…", "Продукт отделяют…".

## Критерии отбора источников (строго)
Отбирай только источники, в которых есть реальные технологические подробности, например:
- "Production/Manufacture/Process/Industrial preparation" раздел;
- описание стадий процесса / flow description / flowsheet (хотя бы текстом);
- сырьё/реагенты/условия/оборудование;
- handbook / учебник / технологический обзор / патент / тех. бюллетень.

Избегай источников без техподробностей.

## ВАЖНО: требование "LLM-readable"
Выбирай ТОЛЬКО такие источники, которые можно прочитать напрямую:
- без логина/paywall/капчи;
- HTML страница или текстовый PDF (текст выделяемый; не скан-картинка).
Если источник не читается — НЕ включай.

## Особое требование: "максимально цитатно, но короткими фрагментами"
Тебе нужно сделать описание максимально "привязанным" к исходнику:
- в самом технологическом описании вставляй МНОГО коротких дословных фрагментов в кавычках «…» (каждый фрагмент до ~20 слов);
- затем отдельно дай блок "Доказательные фрагменты" — список коротких дословных фраз (каждая до ~20 слов), покрывающих ВСЕ ключевые шаги процесса.
Если ты не можешь найти подтверждающие фразы в тексте — источник НЕ подходит.

## Запрос
Найди ${maxItems} лучших источников с описанием промышленного процесса получения "${productName}".
Язык результата неограничен.
Не задавай вопросов. Не добавляй комментариев. Выводи только то, что запрошено ниже.
Максимизируй подробность; ограничение только по количеству токенов вывода.

## Формат вывода (СТРОГО JSON)
Верни ТОЛЬКО JSON объекта вида:
{
  "items": [
    {
      "title": "...",
      "url": "https://....",
      "access_hint": "open html" | "text pdf",
      "technology_description": "...",
      "inputs_outputs_hint": ["..."],
      "evidence_snippets": ["«...»", "..."]
    }
  ]
}
Источник 1
URL: <реальный URL>
access_hint: open html | text pdf
Название: <если есть>
Тип источника: patent | handbook | article | tech bulletin | standard | org report | other

Технологическое описание (максимально подробное):
Пиши развернутым связным текстом (несколько абзацев), в логике технологической схемы:
- сначала входное сырьё и подготовка;
- затем реакционный блок;
- затем разделение/очистка;
- затем финиширование (если есть);
- затем побочки/примеси и обращение с ними (если есть);
- затем утилиты/эко-контур (если есть).
Встраивай много коротких дословных фрагментов «…» прямо в описание, рядом с соответствующими стадиями.

Входы/выходы (только если явно указаны):
Входы: ...
Основной продукт: ...
Побочные/отходы: ...

Доказательные фрагменты (короткие дословные, до ~20 слов каждый):
- «...»
- «...»
- «...»
(Дай как можно больше фрагментов в пределах лимита вывода, чтобы они покрывали все ключевые стадии и параметры.)

Где в источнике (если можно определить по тексту):
Раздел/заголовок/страницы: ...

---
Источник 2
(повтори тот же формат)
...

## Правила честности
- Не выдумывай. Если параметр/стадия/реагент не указаны — не добавляй.
- Если источник не открывается/не читается/текст не извлекается — исключай.
- Если не удаётся набрать достаточно подтверждающих коротких фрагментов — исключай.
`.trim();
}

