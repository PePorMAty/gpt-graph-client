export function getDefaultStepSourcesPrompt(
  direction: "up" | "down",
  productName: string,
  maxItems: number,
): string {
  if (direction === "up") {
    return "// Step UP пока не реализован — серверный роут вернёт заглушку step-up not implemented yet";
  }
  return buildStepSourcesPromptDown(productName, maxItems);
}
