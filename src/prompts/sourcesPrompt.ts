export function getDefaultSourcesPrompt(
  direction: "up" | "down",
  productName: string,
  maxItems: number,
): string {
  return direction === "up"
    ? buildSourcesPromptUp(productName, maxItems)
    : buildSourcesPrompt(productName, maxItems);
}

