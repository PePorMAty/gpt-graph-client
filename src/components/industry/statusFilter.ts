// Отбор записей реестра по статусу — общий для обеих панелей ГИСП.
//
// Один и тот же переключатель стоит в панели графа (список всех записей) и в
// карточке узла (производители одного продукта). Держать его описание в двух
// местах значило бы однажды получить «Архив» в одной панели и «В архиве» в
// другой, а список статусов приходит с сервера один.

/** Что показываем: всё, только действующие записи или только прекращённые. */
export type StatusFilter = "all" | "active" | "archived";

/** Порядок и подписи кнопок. Порядок один во всех панелях. */
export const STATUS_FILTERS: Array<[StatusFilter, string]> = [
  ["all", "Все"],
  ["active", "Действует"],
  ["archived", "Архив"],
];

/**
 * Подходит ли запись под отбор.
 *
 * Статус приходит с сервера строкой: «active» у действующих, у прекращённых —
 * что угодно другое. Поэтому сравниваем с «active», а не с «archived»: так
 * незнакомый статус попадёт в архив, а не пропадёт из обоих списков.
 */
export const matchesStatus = (
  status: string | null | undefined,
  filter: StatusFilter,
): boolean => {
  if (filter === "all") return true;
  const active = status === "active";
  return filter === "active" ? active : !active;
};
